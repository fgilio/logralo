    */

    'disks' => [

        'local' => [
            'driver' => 'local',
            'root' => storage_path('app/private'),
            'serve' => true,
            'throw' => false,
            'report' => false,
        ],

        'public' => [
            'driver' => 'local',
            'root' => storage_path('app/public'),
            'url' => mb_rtrim((string) env('APP_URL', 'http://localhost'), '/').'/storage',
            'visibility' => 'public',
            'throw' => false,
            'report' => false,
        ],

        /*
         * Goal photos in local development and in CI. Production points
         * LOGRALO_PHOTO_DISK at the Laravel Cloud bucket instead, which the
         * framework injects from LARAVEL_CLOUD_DISK_CONFIG.
         *
         * 'serve' registers a /photos route for this disk, so local dev needs
         * no storage:link, and the public visibility means those URLs need no
         * signature.
         */
