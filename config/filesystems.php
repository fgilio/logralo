            'driver' => 'local',
            'root' => storage_path('app/photos'),
            // Relative on purpose: the served route only ever needs the path,
            // and a hardcoded host breaks the moment the app answers on
            // another one (127.0.0.1 in dev, a preview domain in review).
            'url' => '/photos',
            'visibility' => 'public',
            'serve' => true,
            'throw' => false,
            'report' => false,
        ],

        's3' => [
